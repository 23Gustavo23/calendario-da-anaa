function openMessage(dateKey) {

    const message =
        specialMessages[dateKey];

    const saturdayMessage =
        saturdayMessages[dateKey];

    const photo =
        photos[dateKey];


    const parts =
        dateKey.split("-");


    const year =
        Number(parts[0]);

    const month =
        Number(parts[1]) - 1;

    const day =
        Number(parts[2]);


    modalDate.textContent =
        `${day} de ${months[month]} de ${year}`;


    /* MENSAGEM */

    if (message) {

        modalTitle.textContent =
            message.title;

        modalContent.textContent =
            message.message;

    }

    else if (saturdayMessage) {

        modalTitle.textContent =
            saturdayMessage.title;

        modalContent.textContent =
            saturdayMessage.message;

    }

    else {

        modalTitle.textContent =
            "Uma mensagem para você ♡";

        modalContent.textContent =
            "Aqui vai uma frase especial para este dia...";

    }


    /* FOTOS */

    modalPhotoContainer.innerHTML = "";


    if (photo) {

        modalPhotoContainer.classList.remove(
            "hidden"
        );


        const photoList =
            Array.isArray(photo)
                ? photo
                : [photo];


        photoList.forEach(
            (photoPath) => {

                const image =
                    document.createElement("img");

                image.src =
                    photoPath;

                image.alt =
                    "Foto especial";

                image.classList.add(
                    "modal-gallery-photo"
                );

                modalPhotoContainer.appendChild(
                    image
                );

            }
        );

    }

    else {

        modalPhotoContainer.classList.add(
            "hidden"
        );

    }


    messageModal.classList.remove(
        "hidden"
    );

}


